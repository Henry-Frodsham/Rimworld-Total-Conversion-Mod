"""SoundDefs for the generated cyberware / quickhack / melee audio.

python Source/Tools/gen_sounds.py [--source D:/RimworldSounds] [--install]

Reads <source>/sounds.json (the sound manifest). One SoundDef per manifest entry, named RPC_Snd_<CamelCaseId>
(sandevistan_on -> RPC_Snd_SandevistanOn), playing every clip in the entry's folder. Output (overwritten every run):
    Common/Defs/Sounds/Generated_Sounds.xml
--install also copies <source>/output/Sounds/RimPunk/<folder>/*.ogg into Common/Sounds, replacing the clips already
in those folders (a stale .wav or .ogg of an older take would otherwise play too).

Not generated here: weapon firing and the arm launcher (import_weapon_sounds.py), and the transport / callout entries, which already have
SoundDefs in Sounds_TraumaTeam.xml. Those are only copied by --install.
"""
import argparse
import json
import re
import shutil
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Common/Defs/Sounds/Generated_Sounds.xml'
SOUNDS = ROOT / 'Common/Sounds'

SKIP_PACKS = {'weapons', 'transport', 'callouts'}
IMPORTED = set(json.loads((ROOT / 'Source/Tools/data/weapon_sounds.json').read_text(encoding='utf-8'))['profiles'])   # import_weapon_sounds.py owns these
# (volumeRange, distRange) per kind; weapons use 28~30 / 12~65, these sit a little under a gunshot
ONE_SHOT = ('26~30', '10~50')
LOOP = ('18~22', '8~35')
SELF_UI = ('30~30', '0~0')   # played on camera


def camel(id_):
    return ''.join(p.capitalize() for p in id_.split('_'))


def def_name(id_):
    return 'RPC_Snd_' + camel(id_)


def one_shot(name, folder):
    vol, dist = ONE_SHOT
    return f'''  <SoundDef>
    <defName>{name}</defName>
    <context>MapOnly</context>
    <maxVoices>8</maxVoices>
    <maxSimultaneous>3</maxSimultaneous>
    <priorityMode>PrioritizeNewest</priorityMode>
    <subSounds>
      <li>
        <grains>
          <li Class="AudioGrain_Folder">
            <clipFolderPath>{escape(folder)}</clipFolderPath>
          </li>
        </grains>
        <volumeRange>{vol}</volumeRange>
        <pitchRange>0.97~1.03</pitchRange>
        <distRange>{dist}</distRange>
        <onCamera>false</onCamera>
        <tempoAffectedByGameSpeed>false</tempoAffectedByGameSpeed>
      </li>
    </subSounds>
  </SoundDef>
'''


def loop(name, folder):
    vol, dist = LOOP
    return f'''  <SoundDef>
    <defName>{name}</defName>
    <context>MapOnly</context>
    <sustain>true</sustain>
    <sustainFadeoutTime>0.35</sustainFadeoutTime>
    <maxVoices>4</maxVoices>
    <maxSimultaneous>2</maxSimultaneous>
    <priorityMode>PrioritizeNewest</priorityMode>
    <subSounds>
      <li>
        <grains>
          <li Class="AudioGrain_Folder">
            <clipFolderPath>{escape(folder)}</clipFolderPath>
          </li>
        </grains>
        <volumeRange>{vol}</volumeRange>
        <distRange>{dist}</distRange>
        <onCamera>false</onCamera>
        <sustainLoop>true</sustainLoop>
        <sustainAttack>0.05</sustainAttack>
        <sustainSkipFirstAttack>false</sustainSkipFirstAttack>
        <sustainRelease>0.2</sustainRelease>
        <tempoAffectedByGameSpeed>false</tempoAffectedByGameSpeed>
      </li>
    </subSounds>
  </SoundDef>
'''


def on_camera(name, folder):
    """Alerts with no place in the world (NetWatch trace)."""
    vol, _ = SELF_UI
    return f'''  <SoundDef>
    <defName>{name}</defName>
    <context>Any</context>
    <maxSimultaneous>1</maxSimultaneous>
    <subSounds>
      <li>
        <grains>
          <li Class="AudioGrain_Folder">
            <clipFolderPath>{escape(folder)}</clipFolderPath>
          </li>
        </grains>
        <volumeRange>{vol}</volumeRange>
        <onCamera>true</onCamera>
        <tempoAffectedByGameSpeed>false</tempoAffectedByGameSpeed>
      </li>
    </subSounds>
  </SoundDef>
'''


ON_CAMERA = {'qh_trace_alert'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--source', type=Path, default=Path('D:/RimworldSounds'))
    ap.add_argument('--install', action='store_true')
    args = ap.parse_args()
    manifest = json.loads((args.source / 'sounds.json').read_text(encoding='utf-8'))
    defs, names = [], []
    for s in manifest['sounds']:
        if s['pack'] in SKIP_PACKS or s['id'] in IMPORTED:
            continue
        name = def_name(s['id'])
        names.append(name)
        build = on_camera if s['id'] in ON_CAMERA else loop if s.get('loop') else one_shot
        defs.append(build(name, s['folder']))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by Source/Tools/gen_sounds.py. Do not edit; change the generator and rerun. -->\n<Defs>\n'
                   + ''.join(defs) + '</Defs>\n', encoding='utf-8', newline='\n')
    print(f'{len(defs)} SoundDefs -> {OUT.relative_to(ROOT)}')
    if args.install:
        install(args.source, manifest)


def install(source, manifest):
    copied = removed = 0
    for s in manifest['sounds']:
        if s['pack'] == 'weapons' or s['id'] in IMPORTED:
            continue    # the importer owns these (it cuts single shots out of raw/)
        src = source / 'output/Sounds' / s['folder']
        if not src.is_dir():
            print('  missing', s['folder'])
            continue
        dest = SOUNDS / s['folder']
        dest.mkdir(parents=True, exist_ok=True)
        wanted = {p.name for p in src.glob('*.ogg')}
        for old in dest.iterdir():
            if old.suffix.lower() in ('.ogg', '.wav', '.mp3') and old.name not in wanted and re.match(re.escape(s['id']) + r'_\d+', old.name):
                old.unlink()
                removed += 1
        for clip in src.glob('*.ogg'):
            shutil.copy2(clip, dest / clip.name)
            copied += 1
    print(f'installed {copied} clips, removed {removed} stale ones')


if __name__ == '__main__':
    main()
